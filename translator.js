let currentLang = localStorage.getItem('siteLanguage') || 'en';
let googleScriptLoaded = false;

function loadGoogleTranslateScript() {
    if (googleScriptLoaded) return;
    googleScriptLoaded = true;
    const script = document.createElement('script');
    script.src = '//translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
    script.async = true;
    document.body.appendChild(script);
}

function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'ja' : 'en';
    localStorage.setItem('siteLanguage', currentLang);
    applyLanguage(currentLang);
    if (!googleScriptLoaded) {
        setTimeout(loadGoogleTranslateScript, 100);
    }
}

function applyLanguage(lang) {
    document.documentElement.lang = lang;
    const btn = document.getElementById('langToggleBtn');
    if (btn) {
        btn.innerHTML = lang === 'en' ? '🌐 日本語' : '🌐 English';
    }

    // Google Translate Combo Fallback Trigger
    const googleCombo = document.querySelector('.goog-te-combo');
    if (googleCombo) {
        googleCombo.value = lang === 'ja' ? 'ja' : 'en';
        googleCombo.dispatchEvent(new Event('change'));
    }

    // Instant zero-latency UI Translation via data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            elem.innerText = translations[lang][key];
        }
    });

    // Translate Placeholders
    const inputs = document.querySelectorAll('[data-i18n-placeholder]');
    inputs.forEach(input => {
        const key = input.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            input.placeholder = translations[lang][key];
        }
    });

    // Update typing text array dynamically on index page
    if (window.updateTypingArray) {
        window.updateTypingArray(lang);
    }
}

// Google Translate Callback
function googleTranslateElementInit() {
    if (window.google && window.google.translate) {
        new window.google.translate.TranslateElement({
            pageLanguage: 'en',
            includedLanguages: 'en,ja',
            autoDisplay: false
        }, 'google_translate_element');
    }
}

// Apply instant translation as soon as DOM loads
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => applyLanguage(currentLang));
} else {
    applyLanguage(currentLang);
}
